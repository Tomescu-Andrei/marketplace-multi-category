CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (btrim(name) <> ''),
    slug VARCHAR(100) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    parent_id BIGINT REFERENCES categories(id),
    CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX categories_parent_id_idx ON categories(parent_id);

CREATE TABLE category_attributes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    name VARCHAR(100) NOT NULL,
    code VARCHAR(100) NOT NULL CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    data_type VARCHAR(10) NOT NULL CHECK (data_type IN ('TEXT', 'NUMBER', 'BOOLEAN')),
    required BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (category_id, code)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    display_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES users(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    title VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''),
    description VARCHAR(10000) NOT NULL CHECK (btrim(description) <> ''),
    listing_type VARCHAR(20) NOT NULL CHECK (listing_type IN ('FIXED_PRICE', 'AUCTION')),
    price NUMERIC(14, 2) CHECK (price > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SOLD', 'CLOSED')),
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(attributes) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (listing_type <> 'FIXED_PRICE' OR price IS NOT NULL)
);

CREATE INDEX listings_category_id_idx ON listings(category_id);
CREATE INDEX listings_seller_id_idx ON listings(seller_id);
CREATE INDEX listings_created_at_idx ON listings(created_at DESC, id DESC);
